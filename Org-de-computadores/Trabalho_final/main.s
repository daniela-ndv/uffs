# =============================================================================
# swap(int* a, int* b)
# =============================================================================
swap:
    lw   t0, 0(a0)
    lw   t1, 0(a1)
    sw   t1, 0(a0)
    sw   t0, 0(a1)
    ret


# =============================================================================
# partition(int arr[], int low, int high) → retorna índice do pivô
# =============================================================================
partition:
    addi sp, sp, -32
    sw   ra,  28(sp)
    sw   s0,  24(sp)       # arr
    sw   s1,  20(sp)       # low
    sw   s2,  16(sp)       # high
    sw   s3,  12(sp)       # i
    sw   s4,   8(sp)       # j
    sw   s5,   4(sp)       # pivot

    mv   s0, a0
    mv   s1, a1
    mv   s2, a2

    slli t0, s2, 2
    add  t0, s0, t0
    lw   s5, 0(t0)         # pivot = arr[high]

    addi s3, s1, -1        # i = low - 1
    mv   s4, s1            # j = low

partition_loop:
    addi t0, s2, -1
    bgt  s4, t0, partition_loop_end

    slli t0, s4, 2
    add  t0, s0, t0
    lw   t1, 0(t0)
    bgt  t1, s5, partition_skip

    addi s3, s3, 1
    slli a0, s3, 2
    add  a0, s0, a0
    slli a1, s4, 2
    add  a1, s0, a1
    call swap

partition_skip:
    addi s4, s4, 1
    j    partition_loop

partition_loop_end:
    addi t0, s3, 1
    slli a0, t0, 2
    add  a0, s0, a0
    slli a1, s2, 2
    add  a1, s0, a1
    call swap

    addi a0, s3, 1         # retorna i + 1

    lw   ra,  28(sp)
    lw   s0,  24(sp)
    lw   s1,  20(sp)
    lw   s2,  16(sp)
    lw   s3,  12(sp)
    lw   s4,   8(sp)
    lw   s5,   4(sp)
    addi sp, sp, 32
    ret


